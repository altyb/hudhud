#!/usr/bin/env python3
"""Hudhud logo: Gemini source src/mark.jpg -> every size and variant. Needs potrace, Pillow, rsvg-convert.
Usage: python3 design/logo/trace.py
Writes svg/ (tile, light tile, tintable mark, black mono), Android launcher (colour + themed + round uses same),
a tintable in-app mark, and the 512 px Play / F-Droid icon."""
import pathlib, re, subprocess, tempfile
from PIL import Image

HERE = pathlib.Path(__file__).parent; ROOT = HERE.parent.parent
RES = ROOT / "app/src/main/res"
TEAL, CREAM = "#1C4A5C", "#F2EEE0"
BOX = (500, 430, 1640, 1580)   # the bird only: the tile's white corners must stay out of the trace

im = Image.open(HERE / "src/mark.jpg").convert("L").crop(BOX); W, H = im.size
mask = im.point(lambda v: 0 if v > 150 else 255)                                  # bird = black
with tempfile.TemporaryDirectory() as t:
    pbm = pathlib.Path(t, "a.pbm"); mask.convert("1").save(pbm)
    o = subprocess.run(["potrace", str(pbm), "-b", "svg", "-t", "40", "-a", "1.2", "-O", "1", "--flat", "-o", "-"], capture_output=True, text=True, check=True).stdout
D = " ".join(" ".join(re.findall(r'<path d="([^"]+)"', o)).split())   # potrace units: tenths of a pixel, y up

px = mask.load(); pts = [(x, y) for y in range(0, H, 4) for x in range(0, W, 4) if px[x, y] == 0]
cx = sum(x for x, _ in pts) / len(pts); cy = sum(y for _, y in pts) / len(pts)   # centre of mass, not bounding box
dist = sorted(((x - cx) ** 2 + (y - cy) ** 2) ** .5 for x, y in pts)
R_FAR = dist[int(len(dist) * .998)]                                              # ignores the thin bill tip

X0, Y0, X1, Y1 = mask.point(lambda v: 255 if v == 0 else 0).getbbox()

def place(size, centre=54):
    """Transform that centres the bird's bounding box on `centre`, its longer side `size` of the 108 grid.
    Box, not centre of mass: the long bill and the crest must clear the squircle mask on every phone."""
    f = size / max(X1 - X0, Y1 - Y0)
    return centre - (X0 + X1) / 2 * f, centre - (Y0 + Y1) / 2 * f + H * f, .1 * f

def svg_group(fill, radius, tile=None):
    x, y, s = place(radius)
    bg = f'<rect width="108" height="108" rx="24" fill="{tile}"/>' if tile else ""
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">{bg}<g transform="translate({x:.2f},{y:.2f}) scale({s:.5f},{-s:.5f})"><path fill="{fill}" fill-rule="evenodd" d="{D}"/></g></svg>\n'

def android(fill, radius, dp=108):
    x, y, s = place(radius)
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by design/logo/trace.py -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{dp}dp" android:height="{dp}dp" android:viewportWidth="108" android:viewportHeight="108">\n'
            f'    <group android:translateX="{x:.3f}" android:translateY="{y:.3f}" android:scaleX="{s:.5f}" android:scaleY="{-s:.5f}">\n'
            f'        <path android:fillColor="{fill}" android:fillType="evenOdd" android:pathData="{D}"/>\n    </group>\n</vector>\n')

out = HERE / "svg"; out.mkdir(exist_ok=True)
(out / "hudhud.svg").write_text(svg_group(CREAM, 62, TEAL))            # app icon, dark tile
(out / "hudhud-light.svg").write_text(svg_group(TEAL, 62, CREAM))      # same on a light tile
(out / "hudhud-mark.svg").write_text(svg_group("currentColor", 100))    # bird alone, tinted by CSS / README
(out / "hudhud-black.svg").write_text(svg_group("#000000", 100))        # one-colour print / stamp

(RES / "drawable/ic_launcher_foreground.xml").write_text(android(CREAM, 56))             # adaptive, Android 8+ (bird 56 of 108: inside the 66 safe circle and any squircle)
(RES / "drawable/ic_launcher_monochrome.xml").write_text(android("#FFFFFFFF", 56))       # themed icon, Android 13+
(RES / "drawable/ic_hudhud_mark.xml").write_text(android("#FF000000", 108, dp=96))        # in-app, tint from theme

# Play / F-Droid icon: 512 px full-bleed square (the store rounds it), and a rounded 1024 for the README.
for size, name, rx, dest in ((512, "icon.png", 0, ROOT / "fastlane/metadata/android/en-US/images"), (1024, "logo.png", 24, ROOT / "docs")):
    s = svg_group(CREAM, 70, TEAL).replace(f'rx="24"', f'rx="{rx}"')
    dest.mkdir(parents=True, exist_ok=True)
    subprocess.run(["rsvg-convert", "-w", str(size), "-h", str(size), "-o", str(dest / name)], input=s, text=True, check=True)
print("ok", len(D))

# Banner for the README and the store feature graphic: 1024x500, bird left, name and one line right.
x, y, s = place(300, 0)   # size in pixels here, bird centre at 0,0 before the move below
banner = (f'<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="500" viewBox="0 0 1024 500"><rect width="1024" height="500" fill="{TEAL}"/>'
          f'<g transform="translate({x + 235:.1f},{y + 250:.1f}) scale({s:.5f},{-s:.5f})"><path fill="{CREAM}" fill-rule="evenodd" d="{D}"/></g>'
          '<text x="495" y="262" font-family="Noto Sans, DejaVu Sans, sans-serif" font-weight="700" font-size="116" fill="#F2A65A">Hudhud</text>'
          f'<text x="497" y="318" font-family="Noto Sans, DejaVu Sans, sans-serif" font-size="27" fill="#C5D5DE">Private English and Arabic keyboard</text></svg>')
for dest in (ROOT / "docs/brand/banner.png", ROOT / "fastlane/metadata/android/en-US/images/featureGraphic.png"):
    subprocess.run(["rsvg-convert", "-o", str(dest)], input=banner, text=True, check=True)
